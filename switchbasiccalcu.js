let op='/'
let num1=20
let num2=30
switch(op)
{
    case  '+':console.log(num1+num2);
    break;
    case  '-':console.log(num1-num2);
    break;
    case  '*':console.log(num1*num2);
    break;
    case  '/':console.log(num1/num2);
    break;
    case  '%':console.log(num1%num2);
    break;
    default:console.log('invalid operator');
}